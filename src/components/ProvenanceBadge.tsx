/**
 * Provenance / Data Status Badge Component
 * Team: Quanta Buddies - NASA Space Apps Challenge 2026
 *
 * Transparently and honestly distinguishes data lineage across the UI:
 * - LIVE_NASA: Real-time telemetry from NASA Open API
 * - HISTORICAL_NASA: Verified archival observation from NASA Planetary Data System (PDS)
 * - DERIVED: Analytical/geodetic calculations derived from official NASA datums (MOLA, Haversine, slope)
 * - SIMULATED: Deterministic physical simulation or synthetic model (e.g. xEVA suit vitals, micro-relief)
 * - DATA_UNAVAILABLE: Telemetry not present (e.g. uncrewed robotic phase biometrics)
 * - AI_GENERATED: Analytical output generated by Gemini AI model
 * - FALLBACK: Verified empirical baseline or offline archival dataset
 */

import React from 'react';
import { Radio, Sparkles, Cpu, AlertTriangle, Database, AlertCircle, Compass, Calculator } from 'lucide-react';
import { DataProvenance } from '../types';

interface ProvenanceBadgeProps {
  provenance?: DataProvenance | string;
  size?: 'xs' | 'sm' | 'md';
  showLabel?: boolean;
  className?: string;
}

export const PROVENANCE_LABELS: Record<DataProvenance, { label: string; desc: string }> = {
  LIVE_NASA: {
    label: 'LIVE NASA API',
    desc: 'Live telemetry stream from active NASA Open API endpoint',
  },
  HISTORICAL_NASA: {
    label: 'HISTORICAL PDS',
    desc: 'Verified archival observation from NASA Planetary Data System (PDS)',
  },
  DERIVED: {
    label: 'DERIVED METRIC',
    desc: 'Mathematical calculation derived from official NASA planetary datums (MOLA / IAU 2000)',
  },
  SIMULATED: {
    label: 'SIMULATED MODEL',
    desc: 'Deterministic physical simulation or synthetic baseline model (clearly labeled)',
  },
  DATA_UNAVAILABLE: {
    label: 'DATA UNAVAILABLE',
    desc: 'Telemetry unavailable: uncrewed phase, restricted telemetry, or offline sensor',
  },
  AI_GENERATED: {
    label: 'AI GENERATED',
    desc: 'Grounded analytical output synthesized by Gemini AI model',
  },
  FALLBACK: {
    label: 'PDS FALLBACK',
    desc: 'Verified PDS static baseline archive (Sol 1240 Jezero MEDA / InSight APSS)',
  },
};

export const ProvenanceBadge: React.FC<ProvenanceBadgeProps> = ({
  provenance = 'HISTORICAL_NASA',
  size = 'sm',
  showLabel = true,
  className = '',
}) => {
  // Normalize string
  let normProv: DataProvenance = 'HISTORICAL_NASA';
  if (provenance === 'LIVE_NASA') normProv = 'LIVE_NASA';
  else if (provenance === 'HISTORICAL_NASA') normProv = 'HISTORICAL_NASA';
  else if (provenance === 'DERIVED') normProv = 'DERIVED';
  else if (provenance === 'SIMULATED') normProv = 'SIMULATED';
  else if (provenance === 'DATA_UNAVAILABLE') normProv = 'DATA_UNAVAILABLE';
  else if (provenance === 'AI_GENERATED') normProv = 'AI_GENERATED';
  else if (provenance === 'FALLBACK') normProv = 'FALLBACK';

  const meta = PROVENANCE_LABELS[normProv] || PROVENANCE_LABELS.HISTORICAL_NASA;

  let colorClasses = '';
  let Icon: React.ComponentType<{ className?: string }> = Database;

  switch (normProv) {
    case 'LIVE_NASA':
      colorClasses =
        'bg-emerald-950/80 border-emerald-400/80 text-emerald-300 shadow-[0_0_12px_rgba(16,185,129,0.4)] backdrop-blur-md';
      Icon = Radio;
      break;
    case 'HISTORICAL_NASA':
      colorClasses =
        'bg-cyan-950/80 border-cyan-400/60 text-cyan-300 shadow-[0_0_12px_rgba(6,182,212,0.35)] backdrop-blur-md';
      Icon = Database;
      break;
    case 'DERIVED':
      colorClasses =
        'bg-sky-950/80 border-sky-400/70 text-sky-300 shadow-[0_0_12px_rgba(56,189,248,0.35)] backdrop-blur-md';
      Icon = Calculator;
      break;
    case 'SIMULATED':
      colorClasses =
        'bg-amber-950/70 border-amber-500/60 text-amber-300 shadow-[0_0_10px_rgba(245,158,11,0.25)] backdrop-blur-md';
      Icon = Cpu;
      break;
    case 'DATA_UNAVAILABLE':
      colorClasses =
        'bg-slate-900/90 border-slate-700/80 text-slate-400 shadow-[0_0_10px_rgba(148,163,184,0.2)] backdrop-blur-md';
      Icon = AlertCircle;
      break;
    case 'AI_GENERATED':
      colorClasses =
        'bg-purple-950/70 border-purple-400/60 text-purple-300 shadow-[0_0_12px_rgba(168,85,247,0.35)] backdrop-blur-md';
      Icon = Sparkles;
      break;
    case 'FALLBACK':
      colorClasses =
        'bg-cyan-950/70 border-cyan-500/50 text-cyan-300 shadow-[0_0_10px_rgba(6,182,212,0.25)] backdrop-blur-md';
      Icon = Database;
      break;
    default:
      colorClasses =
        'bg-cyan-950/80 border-cyan-400/60 text-cyan-300 shadow-[0_0_12px_rgba(6,182,212,0.35)] backdrop-blur-md';
      Icon = Database;
      break;
  }

  const sizeClasses =
    size === 'xs'
      ? 'px-1.5 py-0.5 text-[9px] gap-1'
      : size === 'md'
      ? 'px-2.5 py-1 text-xs gap-1.5'
      : 'px-2 py-0.5 text-[10px] gap-1.5';

  const iconSizes =
    size === 'xs' ? 'w-2.5 h-2.5' : size === 'md' ? 'w-3.5 h-3.5' : 'w-3 h-3';

  return (
    <span
      className={`inline-flex items-center font-mono font-bold uppercase rounded-md border tracking-wider transition-all duration-300 select-none hover:brightness-110 ${sizeClasses} ${colorClasses} ${className}`}
      title={meta.desc}
      data-provenance={normProv}
    >
      <Icon className={`${iconSizes} shrink-0 ${normProv === 'LIVE_NASA' ? 'animate-pulse text-emerald-400' : ''}`} />
      {showLabel && <span>{meta.label}</span>}
      {normProv === 'LIVE_NASA' && (
        <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 animate-ping shrink-0" />
      )}
    </span>
  );
};
